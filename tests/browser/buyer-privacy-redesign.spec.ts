test('compact cookie choice persists, preferences reopen and reset does not clear the cart',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/products');await page.locator('.pc-add').first().click()
  await page.evaluate(key=>localStorage.removeItem(key),COOKIE_CHOICE_KEY);await page.reload()
  const panel=page.getByRole('region',{name:'Your privacy choices'})
  await expect(panel).toBeVisible()
  expect((await panel.boundingBox())!.height).toBeLessThan(285)
  await panel.getByRole('button',{name:'Essential only',exact:true}).click()
  await page.reload();await expect(panel).toHaveCount(0)
  await page.getByRole('button',{name:'Cookie preferences',exact:true}).click()
  const preferences=page.getByRole('dialog',{name:'Cookie preferences'})
  await expect(preferences).toBeVisible()
  await expect(preferences.getByRole('switch')).toHaveCount(0)
  await preferences.getByRole('button',{name:'Reset saved choice'}).click()
  await expect(panel).toBeVisible()
  await panel.getByRole('button',{name:'Dismiss cookie notice'}).click()
  await page.goto('/cart');await expect(page.getByText('Campus headphones').first()).toBeVisible()
})
