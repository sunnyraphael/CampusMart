import type {Page} from '@playwright/test'
import {test,expect} from '@playwright/test'
import {ids,session} from '../fixture-backend.mjs'

const backend='http://127.0.0.1:54329'
async function confirmPin(page:Page){const dialog=page.getByRole('dialog');await dialog.getByLabel('Transaction PIN',{exact:true}).fill('246810');await dialog.getByRole('button',{name:'Confirm with PIN'}).click()}

test.beforeEach(async({context,request})=>{
  await request.post(`${backend}/__reset`)
  await request.post(`${backend}/__vendor`,{data:{role:'vendor',store:true}})
  await context.addCookies([{name:'sb-127-auth-token',value:'base64-'+Buffer.from(JSON.stringify(session())).toString('base64url'),domain:'127.0.0.1',path:'/',httpOnly:false,sameSite:'Lax'}])
})
async function checkout(page:import('@playwright/test').Page){
  await page.goto('/products')
  await page.locator('.pc-add').first().click()
  await page.goto('/checkout')
  await page.getByRole('checkbox',{name:/I have reviewed/}).check()
  await expect(page.getByRole('button',{name:'Place trial order',exact:true})).toBeEnabled()
  await page.getByLabel('Contact phone',{exact:true}).fill('08012345678')
}

test('trial checkout creates an unpaid test order and completes the full delivery procedure',async({page,request})=>{
  test.setTimeout(90000)
  await checkout(page)
  await page.getByRole('combobox',{name:'Delivery method',exact:true}).selectOption('delivery')
  await page.getByLabel('Delivery address',{exact:true}).fill('Hall A reception')
  await page.getByLabel('Note for the vendor (optional)',{exact:true}).fill('Trial delivery test')
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Trial order created',exact:true})).toBeVisible()
  await expect(page.getByText('Amount charged:',{exact:false})).toContainText('₦0')
  await page.getByRole('link',{name:'Track trial order',exact:true}).click()
  await expect(page.getByText('Trial · no charge',{exact:true})).toBeVisible()
  await expect(page.getByText('Paid',{exact:true})).toHaveCount(0)
  await page.goto(`/vendor/orders/${ids.order}`)
  await expect(page.getByText('TRIAL ORDER · No payment collected.',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Confirm order',exact:true}).click()
  await page.getByRole('button',{name:'Mark as shipped',exact:true}).click()
  await page.goto(`/orders/${ids.order}`)
  await page.getByRole('button',{name:'Generate delivery code',exact:true}).click()
  const code=await page.getByLabel('Your delivery code',{exact:true}).textContent()
  await page.goto(`/vendor/orders/${ids.order}`)
  await page.getByLabel('Buyer’s delivery code',{exact:true}).fill(code!)
  await page.getByRole('button',{name:'Verify code',exact:true}).click()
  await expect(page.getByText(/Delivery code verified ·/)).toBeVisible()
  await page.goto(`/orders/${ids.order}`)
  await page.getByRole('button',{name:'I received this',exact:true}).click()
  await page.getByRole('button',{name:'Confirm receipt',exact:true}).click()
  await expect(page.getByText('Awaiting admin trial approval',{exact:true})).toBeVisible()
  await request.post(`${backend}/__admin`,{data:{enabled:true}})
  await page.goto('/admin/deliveries')
  await page.getByRole('button',{name:'Approve trial delivery',exact:true}).click()
  await page.getByLabel('Your review note',{exact:true}).fill('Completed all trial delivery steps.')
  await page.getByRole('button',{name:'Confirm trial approval',exact:true}).click()
  await confirmPin(page)
  await page.getByRole('link',{name:'Approved',exact:true}).click()
  await expect(page.getByText('Trial completed',{exact:true})).toBeVisible()
  await page.goto('/vendor/earnings')
  await expect(page.locator('.er-hero-amount')).toContainText('₦0')
  await expect(page.getByRole('heading',{name:'No transactions yet',exact:true})).toBeVisible()
  const calls=await(await request.get(`${backend}/__calls`)).json()
  expect(calls.some((c:{path:string;isService:boolean})=>c.path.endsWith('/rpc/cm_create_trial_order')&&c.isService)).toBe(true)
  expect(calls.some((c:{path:string})=>c.path.endsWith('/rpc/create_order'))).toBe(false)
})

test('a lost checkout response keeps the cart and retries the same order once',async({page,request})=>{
  await checkout(page)
  await request.post(`${backend}/__trial`,{data:{loseResponse:true}})
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('alert').filter({hasText:'The trial order result could not be confirmed'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Order summary',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Trial order created',exact:true})).toBeVisible()
  const calls=(await(await request.get(`${backend}/__calls`)).json()).filter((c:{path:string})=>c.path.endsWith('/rpc/cm_create_trial_order'))
  expect(calls).toHaveLength(2);expect(calls[0].requestId).toBe(calls[1].requestId)
  expect((await(await request.get(`${backend}/__trial_state`)).json()).created).toBe(1)
  await page.goto('/cart');await expect(page.getByRole('heading',{name:'Your cart is empty',exact:true})).toBeVisible()
})

test('changed prices require review before a trial order can be placed',async({page,request})=>{
  await checkout(page)
  await request.post(`${backend}/__trial`,{data:{price:13000}})
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('alert').filter({hasText:'Prices changed.'})).toBeVisible()
  await page.getByRole('button',{name:'Refresh prices',exact:true}).click()
  await expect(page.getByText('₦13,260',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Trial order created',exact:true})).toBeVisible()
})

test('an unpaid trial dispute reaches admin review and only simulates a refund',async({page,request})=>{
  test.setTimeout(90000)
  await checkout(page)
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Trial order created',exact:true})).toBeVisible()
  await page.goto(`/vendor/orders/${ids.order}`)
  await page.getByRole('button',{name:'Confirm order',exact:true}).click()
  await page.getByRole('button',{name:'Mark ready for pickup',exact:true}).click()
  await page.goto(`/orders/${ids.order}`)
  await page.getByRole('button',{name:'Report a problem',exact:true}).click()
  await page.getByLabel('Describe the problem',{exact:true}).fill('Testing a trial item that never arrived.')
  await page.getByRole('button',{name:'Submit dispute',exact:true}).click()
  await expect(page.getByText('Trial approval on hold',{exact:true})).toBeVisible()
  await request.post(`${backend}/__admin`,{data:{enabled:true}})
  await page.goto('/admin/disputes')
  await expect(page.getByText('TRIAL ORDER - Dispute decisions are simulated.',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Approve refund',exact:true}).click()
  await page.getByLabel('Your note (saved with the decision)',{exact:true}).fill('Trial refund approval for testing only.')
  await page.getByRole('button',{name:'Confirm refund decision',exact:true}).click()
  await confirmPin(page)
  await expect(page.getByText('Trial dispute decision saved.',{exact:false})).toBeVisible()
  await page.getByRole('tab',{name:'Resolved',exact:true}).click()
  await expect(page.getByText('Refund approved',{exact:true})).toBeVisible()
})

