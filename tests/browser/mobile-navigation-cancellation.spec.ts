import {test,expect} from '@playwright/test'
import {ids,session} from '../fixture-backend.mjs'
const backend='http://127.0.0.1:54329'
test.beforeEach(async({context,request})=>{
  await request.post(`${backend}/__reset`)
  await context.addCookies([{name:'sb-127-auth-token',value:'base64-'+Buffer.from(JSON.stringify(session())).toString('base64url'),domain:'127.0.0.1',path:'/',httpOnly:false,sameSite:'Lax'}])
})
for(const width of [320,390,768])test(`mobile navigation has four tabs and accessible account controls at ${width}px`,async({page,request})=>{
  await page.setViewportSize({width,height:844})
  await request.post(`${backend}/__admin`,{data:{enabled:true}})
  await page.goto('/products')
  const tabs=page.getByRole('navigation',{name:'Main shopping navigation'})
  await expect(tabs.getByRole('link')).toHaveText(['Home','Categories','Listings','Deals'])
  await expect(tabs.getByRole('link',{name:'Listings',exact:true})).toHaveAttribute('aria-current','page')
  const trigger=page.getByRole('button',{name:'Open account and help menu'})
  const search=page.getByRole('search').filter({visible:true})
  expect((await trigger.boundingBox())!.x).toBeGreaterThan((await search.boundingBox())!.x)
  await trigger.click()
  const menu=page.getByRole('menu',{name:'Account and help'})
  await expect(menu.getByRole('menuitem',{name:'Admin workspace'})).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:'Settings & privacy'})).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:'Sign out',exact:true})).toBeVisible()
  const items=await menu.getByRole('menuitem').allTextContents()
  expect(items.indexOf('Sign out')).toBe(items.indexOf('Settings & privacy')+1)
  await page.keyboard.press('Escape');await expect(menu).not.toBeVisible();await expect(trigger).toBeFocused()
  await trigger.click();await menu.getByRole('menuitem',{name:'Settings & privacy'}).click()
  await expect(page).toHaveURL(/\/settings$/)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await trigger.click();await expect(menu).toBeVisible()
  await page.setViewportSize({width:1440,height:950});await expect(menu).not.toBeVisible()
})
test('signed-out mobile menu shows login, while sign out ends an authenticated session',async({page,context})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/products')
  await page.getByRole('button',{name:'Open account and help menu'}).click()
  await page.getByRole('menuitem',{name:'Sign out',exact:true}).click()
  await expect(page).toHaveURL(/\/$/)
  await expect.poll(async()=> (await context.cookies()).some(cookie=>cookie.name==='sb-127-auth-token'&&cookie.value.length>0)).toBe(false)
  await page.getByRole('button',{name:'Open account and help menu'}).click()
  await expect(page.getByRole('menuitem',{name:'Log in',exact:true})).toBeVisible()
  await expect(page.getByRole('menuitem',{name:'Sign out',exact:true})).toHaveCount(0)
  await expect(page.getByRole('menuitem',{name:'Admin workspace'})).toHaveCount(0)
})
test('trial cancellation shows exact zero amounts, can keep the order, and confirms persistently',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/products');await page.locator('.pc-add').first().click();await page.goto('/checkout')
  await page.getByRole('checkbox',{name:/I have reviewed/}).check()
  await page.getByLabel('Contact phone',{exact:true}).fill('08012345678')
  await page.getByRole('button',{name:'Place trial order',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Trial order created',exact:true})).toBeVisible()
  await page.goto(`/orders/${ids.order}`)
  await page.getByRole('button',{name:'Cancellation options',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Cancel this order?'})
  await expect(dialog).toContainText('Refund: ₦0. Service fee retained: ₦0.')
  await dialog.getByRole('button',{name:'Keep order',exact:true}).click();await expect(dialog).not.toBeVisible()
  await page.getByRole('button',{name:'Cancellation options',exact:true}).click()
  await page.getByLabel('Reason (optional)',{exact:true}).fill('Testing cancellation')
  await page.getByRole('button',{name:'Confirm cancellation',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Order cancelled'})).toContainText('no bank refund is needed')
  await page.getByRole('button',{name:'Close cancellation options'}).click()
  await page.reload();await expect(page.getByText('Cancelled',{exact:true})).toBeVisible()
})
test('real paid orders explain refund integration limits without confirming a refund',async({page})=>{
  await page.goto(`/orders/${ids.order}`)
  await page.getByRole('button',{name:'Cancellation options',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Cancel this order?'})
  await expect(dialog).toContainText('not enabled until payment and refund integration')
  await expect(dialog.getByRole('button',{name:'Confirm cancellation'})).toHaveCount(0)
})
test('cart buttons wait for interactivity and empty checkout keeps its page heading',async({request,page})=>{
  // Read the complete SSR stream: disabling scripts leaves Next's streamed
  // suspense replacement unapplied and would only inspect the loading skeleton.
  const response=await request.get('/products')
  expect(response.ok()).toBe(true)
  expect(await response.text()).toMatch(/<button(?=[^>]*class="pc-add)(?=[^>]*disabled)[^>]*>/)
  await page.goto('/checkout')
  await expect(page.getByRole('heading',{name:'Checkout',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Your cart is empty',exact:true})).toBeVisible()
})
