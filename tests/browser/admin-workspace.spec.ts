test('failed summaries show an error and refresh recovers real queue counts',async({page,request})=>{
  await request.post(`${backend}/__fail`,{data:{table:'admin_kyc_queue'}})
  await request.post(`${backend}/__fail`,{data:{table:'support_requests'}})
  await page.goto('/admin')
  await expect(page.locator('.buyer-notice[role=alert]')).toContainText('Some queue summaries could not load')
  await expect(page.locator('.aw-stat').filter({hasText:'Vendor verifications'}).locator('strong')).toHaveText('\u2014')
  await request.post(`${backend}/__recover`,{data:{table:'admin_kyc_queue'}})
  await request.post(`${backend}/__recover`,{data:{table:'support_requests'}})
  await page.getByRole('button',{name:'Refresh',exact:true}).click()
  await expect(page.locator('.buyer-notice[role=alert]')).toHaveCount(0)
  await expect(page.locator('.aw-stat').filter({hasText:'Vendor verifications'}).locator('strong')).toHaveText('1')
})
