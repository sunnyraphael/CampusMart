for(const theme of ['light','dark'])test(`all admin pages fit mobile and desktop in ${theme} mode`,async({page,request})=>{
  test.setTimeout(150000)
  await page.addInitScript(value=>localStorage.setItem('campusmart-theme',value),theme)
  for(const width of [320,390,900,1440]){
    await page.setViewportSize({width,height:950})
    for(const [route,title] of [['','Your admin overview'],['deliveries','Delivery approvals'],['verifications','Verifications'],['disputes','Disputes'],['support','Support requests']]){
      await request.post(`${backend}/__vendor`,{data:{itemStatus:route==='disputes'?'disputed':'received'}})
      await request.post(`${backend}/__delivery`,{data:{credited:false,tracking:{code_verified_at:'2026-10-30T10:00:00Z'}}})
      await page.goto(`/admin/${route}`)
      await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('data-theme',theme)
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`${theme} ${width} ${route}`).toBe(true)
      if(width===390||width===1440)await page.screenshot({path:`test-results/admin-${route||'overview'}-${theme}-${width}.png`,fullPage:true})
    }
  }
})
