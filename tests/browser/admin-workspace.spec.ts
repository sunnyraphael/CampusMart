import {test,expect} from '@playwright/test'
import {session,ids} from '../fixture-backend.mjs'
const backend='http://127.0.0.1:54329'
const supportId='aaaaaaaa-1234-4123-8123-aaaaaaaaaaaa'
test.setTimeout(90000)
test.beforeEach(async({request,context})=>{
  await request.post(`${backend}/__reset`)
  await request.post(`${backend}/__admin`,{data:{enabled:true}})
  await request.post(`${backend}/__admin_data`,{data:{kyc:[{seller_id:ids.vendor,store_name:'Campus Store',owner_name:'Test Vendor',owner_email:'vendor@example.test',phone:'08012345678',submitted_at:'2026-10-30T10:00:00Z',selfie_path:null,id_path:null}],support:[{id:supportId,subject:'Pickup question',body:'Where should I collect my order?',status:'open',admin_reply:null,created_at:'2026-10-30T10:00:00Z',order_id:ids.order}]}})
  await context.addCookies([{name:'sb-127-auth-token',value:'base64-'+Buffer.from(JSON.stringify(session())).toString('base64url'),domain:'127.0.0.1',path:'/',httpOnly:false,sameSite:'Lax'}])
})
test('overview links to cases and support search, save and status filter work',async({page,request})=>{
  await page.goto('/admin')
  await expect(page.getByRole('heading',{name:'Your admin overview'})).toBeVisible()
  await page.locator('.aw-review-row').filter({hasText:'Pickup question'}).click()
  await expect(page).toHaveURL(`/admin/support?request=${supportId}#support-${supportId}`,{timeout:30000})
  await page.getByRole('searchbox').fill('doesnotexist')
  await expect(page.getByRole('heading',{name:'No matching requests'})).toBeVisible()
  await page.getByRole('button',{name:'Clear filters'}).click()
  await page.getByLabel('Response to buyer').fill('Please meet the vendor at Hall A reception.')
  await page.locator('.aw-support-card select').selectOption('resolved')
  await request.post(`${backend}/__fail`,{data:{table:'support_requests'}})
  await page.getByRole('button',{name:'Save response'}).click()
  await expect(page.locator('.aw-support-card [role=alert]')).toContainText('Could not update')
  await request.post(`${backend}/__recover`,{data:{table:'support_requests'}})
  await page.getByRole('button',{name:'Save response'}).click()
  await expect(page.getByRole('status',{name:'',exact:true}).filter({hasText:'Response saved.'})).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Response to buyer')).toHaveValue('Please meet the vendor at Hall A reception.')
  await page.getByLabel('Support status filter').selectOption('open')
  await expect(page.getByRole('heading',{name:'No matching requests'})).toBeVisible()
})
test('verification failure stays retryable and a successful review refreshes the queue',async({page,request})=>{
  await page.goto('/admin/verifications')
  await page.getByRole('searchbox').fill('campus vendor')
  await expect(page.locator('.vq-card')).toHaveCount(1)
  await request.post(`${backend}/__fail`,{data:{table:'admin_review_kyc'}})
  await page.getByRole('button',{name:'Approve',exact:true}).click()
  await page.getByRole('button',{name:'Confirm approval',exact:true}).click()
  await expect(page.locator('.vq-err[role=alert]')).toContainText('Fixture request failed')
  await request.post(`${backend}/__recover`,{data:{table:'admin_review_kyc'}})
  await page.getByRole('button',{name:'Confirm approval',exact:true}).click()
  await expect(page.locator('.vq-card')).toHaveCount(0)
})
