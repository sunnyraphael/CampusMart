test('admin can hold and resume review; failed decisions remain retryable', async ({ page, request }) => {
  await request.post(`${backend}/__admin`, { data: { enabled: true } })
  await request.post(`${backend}/__vendor`, { data: { itemStatus: 'delivered' } })
  await request.post(`${backend}/__delivery`, { data: { credited: false } })
  await page.goto('/admin/deliveries')
  await page.getByRole('button', { name: 'Hold for review', exact: true }).click()
  await page.getByLabel('Your review note', { exact: true }).fill('Checking delivery evidence with the buyer.')
  await request.post(`${backend}/__fail`, { data: { table: 'cm_admin_hold_delivery' } })
  await page.getByRole('button', { name: 'Confirm hold', exact: true }).click()
  await confirmPin(page)
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Fixture decision unavailable')
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(page.getByRole('button', { name: 'Confirm hold', exact: true })).toBeEnabled()
  await request.post(`${backend}/__recover`, { data: { table: 'cm_admin_hold_delivery' } })
  await page.getByRole('button', { name: 'Confirm hold', exact: true }).click()
  await confirmPin(page)
  await expect(page.getByRole('heading', { name: 'No deliveries in this view' })).toBeVisible()
  await page.getByRole('link', { name: 'On hold', exact: true }).click()
  await expect(page.getByText('Review note: Checking delivery evidence with the buyer.')).toBeVisible()
  await page.getByRole('button', { name: 'Resume review', exact: true }).click()
  await page.getByLabel('Your review note', { exact: true }).fill('Ready for review after speaking to the buyer.')
  await page.getByRole('button', { name: 'Confirm resume', exact: true }).click()
  await confirmPin(page)
  await expect(page.getByRole('heading', { name: 'No deliveries in this view' })).toBeVisible()
  await page.getByRole('link', { name: 'Awaiting review', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Campus headphones', exact: true })).toBeVisible()
})

test('delivery approvals have a matching loader and a recoverable data error', async ({ page, request }) => {
  await request.post(`${backend}/__admin`, { data: { enabled: true } })
  await request.post(`${backend}/__vendor`, { data: { itemStatus: 'delivered' } })
  await request.post(`${backend}/__delivery`, { data: { credited: false } })
  await request.post(`${backend}/__delay`, { data: { table: 'cm_admin_delivery_queue', ms: 2500 } })
  await page.setViewportSize({ width: 320, height: 900 })
  await page.goto('/admin/deliveries', { waitUntil: 'commit' })
  await expect(page.locator('[data-page-skeleton=admin-deliveries]:visible')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.locator('.ot-admin h1:visible')).toHaveText('Delivery approvals', { timeout: 15000 })
  await request.post(`${backend}/__delay`, { data: { table: 'cm_admin_delivery_queue', ms: 0 } })
  await request.post(`${backend}/__fail`, { data: { table: 'cm_admin_delivery_queue' } })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'We could not load this information.', exact: true })).toBeVisible()
  await request.post(`${backend}/__recover`, { data: { table: 'cm_admin_delivery_queue' } })
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Delivery approvals', exact: true })).toBeVisible()
})
