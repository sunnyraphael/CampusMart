for (const theme of ['light', 'dark']) for (const width of [320, 1280]) test(`tracking and approval pages fit ${width}px in ${theme}`, async ({ page, request }) => {
  await request.post(`${backend}/__admin`, { data: { enabled: true } })
  await request.post(`${backend}/__vendor`, { data: { itemStatus: 'delivered' } })
  await request.post(`${backend}/__delivery`, { data: { credited: false } })
  await page.addInitScript(theme => localStorage.setItem('campusmart-theme', theme), theme)
  await page.setViewportSize({ width, height: 900 })
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  for (const path of [`/orders/${ids.order}`, `/vendor/orders/${ids.order}`, '/admin/deliveries']) {
    await page.goto(path)
    await expect(page.locator('main h1, .ad-body h1').first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), path).toBe(true)
    if (width === 320) await page.screenshot({ path: `test-results/previews/tracking-${path.split('/')[1]}-${theme}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
})

