import type {Page} from '@playwright/test'
import { test, expect } from '@playwright/test'
import { ids, session } from '../fixture-backend.mjs'

const backend = 'http://127.0.0.1:54329'
async function confirmPin(page:Page){const dialog=page.getByRole('dialog');await dialog.getByLabel('Transaction PIN',{exact:true}).fill('246810');await dialog.getByRole('button',{name:'Confirm with PIN'}).click()}

test.beforeEach(async ({ context, request }) => {
  await request.post(`${backend}/__reset`)
  await request.post(`${backend}/__vendor`, { data: { role: 'vendor', store: true, itemStatus: 'shipped' } })
  await request.post(`${backend}/__delivery`, { data: { credited: false } })
  await context.addCookies([{ name: 'sb-127-auth-token', value: 'base64-' + Buffer.from(JSON.stringify(session())).toString('base64url'), domain: '127.0.0.1', path: '/', httpOnly: false, sameSite: 'Lax' }])
})

test('buyer generates a private code, vendor verifies it, buyer confirms, admin approves separately', async ({ page, request }) => {
  await page.goto(`/orders/${ids.order}`)
  await expect(page.getByRole('region', { name: 'Delivery tracking' })).toBeVisible()
  await page.getByRole('button', { name: 'Generate delivery code', exact: true }).click()
  const code = await page.getByLabel('Your delivery code', { exact: true }).textContent()
  expect(code).toMatch(/^\d{6}$/)
  await page.goto(`/vendor/orders/${ids.order}`)
  await expect(page.getByLabel('Your delivery code', { exact: true })).toHaveCount(0)
  await page.getByLabel('Buyer’s delivery code', { exact: true }).fill('000000')
  await page.getByRole('button', { name: 'Verify code', exact: true }).click()
  await expect(page.locator('.ot-error[role=alert]')).toContainText('does not match')
  await page.getByLabel('Buyer’s delivery code', { exact: true }).fill(code!)
  await page.getByRole('button', { name: 'Verify code', exact: true }).click()
  await expect(page.getByText(/Delivery code verified ·/)).toBeVisible()
  await page.goto(`/orders/${ids.order}`)
  await expect(page.getByRole('button', { name: 'Generate delivery code', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'I received this', exact: true }).click()
  await expect(page.getByText('It does not release money to the vendor.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Confirm receipt', exact: true }).click()
  await expect(page.getByText('Awaiting admin approval', { exact: true })).toBeVisible()
  await request.post(`${backend}/__admin`, { data: { enabled: true } })
  await page.goto('/admin/deliveries')
  await expect(page.getByRole('button', { name: 'Approve vendor credit', exact: true })).toBeDisabled()
  await expect(page.getByText('Payment verification pending', { exact: true })).toBeVisible()
  await request.post(`${backend}/__delivery`, { data: { verifiedPayment: true } })
  await page.reload()
  await page.getByRole('button', { name: 'Approve vendor credit', exact: true }).click()
  await page.getByLabel('Your review note', { exact: true }).fill('Checked payment, handover and buyer confirmation.')
  await page.getByRole('button', { name: 'Confirm vendor credit', exact: true }).click()
  await confirmPin(page)
  await expect(page.getByRole('heading', { name: 'No deliveries in this view' })).toBeVisible()
  await page.getByRole('link', { name: 'Approved', exact: true }).click()
  await expect(page.getByText('Credited', { exact: true })).toBeVisible()
})

test('delivery details persist when status is advanced, and failures remain retryable', async ({ page, request }) => {
  await page.goto(`/vendor/orders/${ids.order}`)
  await page.getByText('Delivery details & estimated time', { exact: true }).click()
  await page.getByLabel('Courier or rider', { exact: true }).fill('Campus rider')
  await page.getByLabel('Tracking number', { exact: true }).fill('CM-123')
  await page.getByLabel('Courier tracking link', { exact: true }).fill('https://example.test/CM-123')
  await page.getByLabel('Instructions for the buyer', { exact: true }).fill('Meet at Hall A reception.')
  await request.post(`${backend}/__fail`, { data: { table: 'cm_vendor_update_delivery' } })
  await page.getByRole('button', { name: 'Save delivery details', exact: true }).click()
  await expect(page.locator('.ot-error[role=alert]')).toContainText('Fixture request failed')
  await expect(page.getByRole('button', { name: 'Save delivery details', exact: true })).toBeEnabled()
  await request.post(`${backend}/__recover`, { data: { table: 'cm_vendor_update_delivery' } })
  await page.getByRole('button', { name: 'Save delivery details', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Track with courier', exact: true })).toHaveAttribute('href', 'https://example.test/CM-123')
  await page.getByRole('button', { name: 'Report delivery', exact: true }).click()
  await expect(page.getByText('The delivery could not load')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Report delivery', exact: true })).toHaveCount(0)
  await page.goto(`/orders/${ids.order}`)
  await expect(page.getByText('Campus rider', { exact: false })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Track with courier', exact: true })).toBeVisible()
})

